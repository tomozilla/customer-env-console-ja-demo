const R = require("./registry.js");
const versions = require("./versions.json");
const fs = require("fs");
let fail = 0;
const eq = (name, got, want) => { const ok = JSON.stringify(got) === JSON.stringify(want); if (!ok) fail++; console.log(ok ? "ok  " : "FAIL", name, ok ? "" : JSON.stringify(got) + " != " + JSON.stringify(want)); };
const { rows, skipped } = R.parse(fs.readFileSync(__dirname + "/../sample/registry.sample.json", "utf8"));
eq("sample has 5 customers", [rows.length, skipped.length], [5, 0]);
const ev = R.evaluate(rows, versions, "2026-10-27");
const st = Object.fromEntries(ev.map((c) => [c.name, c.status]));
eq("v2 with v2 fingerprint = current", st["acme-demo"], "current");
eq("v1 fingerprint with a hand-made change = drift", st["globex-demo"], "drift");
eq("clean v1 while latest is v2 = behind", st["initech-demo"], "behind");
eq("no fingerprint = unchecked", st["umbrella-demo"], "unchecked");
eq("paused clean v1 = behind, flagged paused and stale", [st["hooli-demo"], ev.find((c) => c.name === "hooli-demo").flags], ["behind", ["確認が古い", "停止中"]]);
eq("client-owned with handover done: no flag", ev.find((c) => c.name === "umbrella-demo").flags, []);
eq("client-owned with handover open is flagged", R.evaluate([{ name: "x", owner: "client", handover: "requested" }], versions, "2026-10-27")[0].flags, ["引き渡し未完了"]);
eq("unknown version", R.evaluate([{ name: "x", owner: "us", version: "v9", fingerprint: "abc" }], versions, "2026-10-27")[0].status, "unknown-version");
eq("summary counts", R.summary(ev), { current: 1, behind: 2, drift: 1, unchecked: 1, "unknown-version": 0 });
const c = R.cost(ev, versions.cost);
eq("cost: 3 running mine -> 25 + (30-10) = 45; 1 client-owned", [c.total, c.running, c.mine, c.clientOwned], [45, 3, 4, 1]);
eq("cost: nothing running = 0", R.cost([{ owner: "us", state: "paused" }], versions.cost).total, 0);
eq("bad json rejected", (() => { try { R.parse("{x"); } catch (e) { return /JSON/.test(e.message); } })(), true);
eq("wrong shape rejected", (() => { try { R.parse('{"a":1}'); } catch (e) { return /必要/.test(e.message); } })(), true);
eq("row without owner skipped and reported", R.parse('[{"name":"a"},{"name":"b","owner":"us"}]').skipped.length, 1);
process.exit(fail ? 1 : 0);
